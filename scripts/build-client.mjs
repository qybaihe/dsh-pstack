#!/usr/bin/env node
/**
 * Bundle `client/src/index.tsx` into `lib/client.js` wrapped in DeepSeek
 * Harness's `window.__ModuleLoader__.load({ id, factory(require) })` envelope.
 *
 * Host-provided React modules (`react`, `react-dom`, `react/jsx-runtime`) stay
 * external; `src/core` pure classifiers (`shell-policy`, `model-routing`,
 * `decision-log`, `catalog`, `panel-rules`, `projection`) are inlined so the
 * browser runs the exact same pure functions with zero Node imports.
 */

import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { build } from 'esbuild'

const root = join(import.meta.dirname, '..')
const entry = join(root, 'client/src/index.tsx')
const outfile = join(root, 'lib/client.js')

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  logLevel: 'warning',
})

const cjsBody = result.outputFiles[0]?.text ?? ''

const wrapped = [
  '// Generated by scripts/build-client.mjs — browser half of @qybaihe/dsh-pstack.',
  'window.__ModuleLoader__.load({',
  '  id: "@qybaihe/dsh-pstack",',
  '  factory(require) {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  cjsBody.trim(),
  '    return module.exports;',
  '  },',
  '});',
  '',
].join('\n')

await mkdir(dirname(outfile), { recursive: true })
await writeFile(outfile, wrapped, 'utf8')
